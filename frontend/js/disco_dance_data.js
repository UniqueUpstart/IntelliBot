function buildTracks(endBeat, frames) {
  const tracks = Object.fromEntries(
    JOINT_NAMES.map((joint) => [joint, [[0, DISCO_DANCE_REST_POSE[joint]]]]),
  );
  frames.forEach(([beat, pose]) => {
    Object.entries(pose).forEach(([joint, value]) => {
      if (!Object.prototype.hasOwnProperty.call(DISCO_DANCE_REST_POSE, joint)) {
        throw new Error(`未知关节轨道: ${joint}`);
      }
      const rest = DISCO_DANCE_REST_POSE[joint];
      const scaled = rest + (value - rest) * EMPHASIS_SCALE[joint];
      const track = tracks[joint];
      const last = track[track.length - 1];
      if (last[0] === beat) last[1] = scaled;
      else track.push([beat, scaled]);
    });
  });
  JOINT_NAMES.forEach((joint) => {
    const track = tracks[joint];
    const last = track[track.length - 1];
    if (last[0] === endBeat) last[1] = DISCO_DANCE_REST_POSE[joint];
    else track.push([endBeat, DISCO_DANCE_REST_POSE[joint]]);
  });
  return tracks;
}

